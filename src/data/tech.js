/** Map any label used in the site ("Java 17", "Laravel 12", "Tailwind CSS"…) to a TECH key. */
const ALIASES = [
  [/^spring modulith/i, "modulith"],
  [/^spring data jpa|^jpa/i, "jpa"],
  [/^spring mvc/i, "springmvc"],
  [/^spring( boot)?/i, "springboot"],
  [/^java\b(?!script)/i, "java"],
  [/^hibernate/i, "hibernate"],
  [/^rest api|^api/i, "api"],
  [/^maven/i, "maven"],
  [/^junit|mockito/i, "junit"],
  [/^php/i, "php"],
  [/^laravel/i, "laravel"],
  [/^blade/i, "blade"],
  [/^vite/i, "vite"],
  [/^html/i, "html"],
  [/^css/i, "css"],
  [/^javascript|^js$/i, "js"],
  [/^typescript|^ts$/i, "ts"],
  [/^react/i, "react"],
  [/^next/i, "next"],
  [/^tailwind/i, "tailwind"],
  [/^bootstrap/i, "bootstrap"],
  [/^alpine/i, "alpine"],
  [/^postgres/i, "postgres"],
  [/^mysql/i, "mysql"],
  [/^sql$/i, "sql"],
  [/^git$/i, "git"],
  [/^github/i, "github"],
  [/^docker/i, "docker"],
  [/^postman/i, "postman"],
  [/^intellij/i, "intellij"],
  [/^vs ?code/i, "vscode"],
  [/^figma/i, "figma"],
  [/^linux/i, "linux"],
];

export function techKey(label = "") {
  if (TECH[label]) return label;
  const hit = ALIASES.find(([re]) => re.test(label.trim()));
  return hit ? hit[1] : null;
}
